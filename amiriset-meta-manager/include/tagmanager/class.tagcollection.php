class TagCollection {
    private array $tags = [];

    public function set(string $key, $value): void {
        $this->tags[$key] = $value;
    }

    public function get(string $key) {
        return $this->tags[$key] ?? null;
    }

    public function getAll(): array {
        return $this->tags;
    }

    public function clear(): void {
        $this->tags = [];
    }
}
